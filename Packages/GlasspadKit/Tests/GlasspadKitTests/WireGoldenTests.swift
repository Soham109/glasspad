import Foundation
import Testing
@testable import GlasspadKit

/// The wire as main wrote it on 16 October 2026 (0.1.2 plus Arrange), frozen. A phone and a Mac from different builds talk to
/// each other, so every message an older build sends must still read the same, and what this
/// build sends for those messages must look the same to the older build.
///
/// To freeze a new version after a release: run the tests with
/// `GLASSPAD_RECORD_WIRE=<path to a new WireGolden_<date>.swift>` and add its list below.
@Suite struct WireGoldenTests {
    static let versions: [(String, [String])] = [("2026-10-16", WireGolden.wire_2026_10_16)]

    private static func object(_ data: Data) throws -> NSObject {
        try JSONSerialization.jsonObject(with: data, options: [.fragmentsAllowed]) as! NSObject
    }

    private static func encoded(_ m: ModeMessage) throws -> Data {
        let e = JSONEncoder()
        e.outputFormatting = [.sortedKeys]
        return try e.encode(m)
    }

    @Test func everyFrozenMessageStillReadsAndIsWrittenTheSameWay() throws {
        for (version, lines) in Self.versions {
            #expect(!lines.isEmpty)
            for line in lines {
                let decoded: ModeMessage
                do {
                    decoded = try JSONDecoder().decode(ModeMessage.self, from: Data(line.utf8))
                } catch {
                    Issue.record("\(version): no longer reads \(line): \(error)")
                    continue
                }
                let again = try Self.encoded(decoded)
                #expect(try Self.object(again) == Self.object(Data(line.utf8)),
                        "\(version): written differently now\n was: \(line)\n now: \(String(decoding: again, as: UTF8.self))")
            }
        }
    }

    /// Every kind of message is in the frozen list, so none can change shape unnoticed.
    @Test func theFrozenListHasEveryKindOfMessage() throws {
        var tags = Set<String>()
        for line in WireGolden.wire_2026_10_16 {
            let object = try JSONSerialization.jsonObject(with: Data(line.utf8)) as? [String: Any]
            tags.insert(try #require(object?["t"] as? String))
        }
        #expect(tags.count == 50, "\(tags.sorted())")
    }

    /// A newer build adds fields beside the ones this build knows, on the message, the Deck,
    /// its pages and its buttons. Those are ignored, never a reason to drop the message.
    @Test func fieldsFromANewerBuildAreIgnored() throws {
        func addField(_ value: Any) -> Any {
            if let d = value as? [String: Any] {
                var out = d.mapValues(addField)
                let isMessage = d["t"] != nil
                let isDeckPart = d["pages"] != nil || (d["id"] != nil && (d["buttons"] != nil || d["symbol"] != nil))
                if isMessage || isDeckPart { out["zzFromANewerBuild"] = ["any": [1, "two", NSNull()]] }
                return out
            }
            if let a = value as? [Any] { return a.map(addField) }
            return value
        }
        for line in WireGolden.wire_2026_10_16 {
            let original = try JSONDecoder().decode(ModeMessage.self, from: Data(line.utf8))
            let widened = try JSONSerialization.data(withJSONObject: addField(JSONSerialization.jsonObject(with: Data(line.utf8))))
            let read = try? JSONDecoder().decode(ModeMessage.self, from: widened)
            #expect(read == original, "dropped or misread with newer fields: \(line)")
        }
    }

    /// Freezes the current wire when GLASSPAD_RECORD_WIRE names a file (see the suite comment).
    @Test func recordWhenAsked() throws {
        guard let path = ProcessInfo.processInfo.environment["GLASSPAD_RECORD_WIRE"] else { return }
        let lines = try CompatibilityTests.everyMessage.map { String(decoding: try Self.encoded($0), as: UTF8.self) }
        let name = URL(fileURLWithPath: path).deletingPathExtension().lastPathComponent
            .replacingOccurrences(of: "WireGolden_", with: "wire_")
        var out = "// Generated by WireGoldenTests (GLASSPAD_RECORD_WIRE). Never edit by hand: a change here\n"
        out += "// means a phone or Mac from that version no longer understands this one.\n"
        out += "extension WireGolden {\n    static let \(name): [String] = [\n"
        for l in lines { out += "        ##\"\(l)\"##,\n" }
        out += "    ]\n}\n"
        try out.write(toFile: path, atomically: true, encoding: .utf8)
    }
}

enum WireGolden {}
